/**
 * Builds src/content/dictionary.ts from the MIT-licensed `an-array-of-english-words` package.
 *
 *   node games/word-rush/scripts/build-dictionary.js
 *
 * Words are 3-8 letters, a-z only, with offensive words removed, sorted and front-coded:
 * each entry is one character giving how many leading letters it shares with the previous word
 * ('0'-'8'), followed by the remaining letters. Entries are separated by newlines.
 *
 * Changing the output changes which words score, so it must ship with a rulesVersion bump.
 */
const fs = require('fs');
const path = require('path');
const words = require('an-array-of-english-words');

const MIN = 3;
const MAX = 8;

// Prefixes that are never part of an innocent word.
const BLOCKED_PREFIXES = [
  'fuck', 'shit', 'cunt', 'bitch', 'nigg', 'nigr', 'whore', 'slut', 'wank', 'twat', 'jizz', 'dildo',
  'faggot', 'retard', 'tranny', 'wetback', 'raghead', 'towelhead', 'porn',
];
// Exact words (prefix matching would also block innocent words like spice, analog or cockpit).
const BLOCKED_EXACT = new Set(
  (
    'ass asses arse arses sex sexy hoe hoes homo homos negro negros negroes jap japs cock cocks dick dicks ' +
    'prick pricks pussy pussies cum cums tit tits titty titties boob boobs anal anus piss pissed pisses pissing ' +
    'rape raped rapes raping rapist rapists nazi nazis coon coons paki pakis spic spics chink chinks gook gooks ' +
    'kike kikes dyke dykes fag fags faggy bastard bastards crap crappy'
  ).split(' ')
);

const isBlocked = (w) => BLOCKED_EXACT.has(w) || BLOCKED_PREFIXES.some((p) => w.startsWith(p));

const list = Array.from(
  new Set(words.filter((w) => /^[a-z]+$/.test(w) && w.length >= MIN && w.length <= MAX && !isBlocked(w)))
).sort();

let prev = '';
const encoded = list
  .map((w) => {
    let shared = 0;
    while (shared < prev.length && shared < w.length && shared < 8 && prev[shared] === w[shared]) shared++;
    prev = w;
    return String(shared) + w.slice(shared);
  })
  .join('\n');

const out = `/* Generated by scripts/build-dictionary.js from an-array-of-english-words (MIT). Do not edit. */
/* ${list.length} words, ${MIN}-${MAX} letters, front-coded. */
export const DICTIONARY_WORD_COUNT = ${list.length};
export const DICTIONARY_DATA = ${JSON.stringify(encoded)};
`;

fs.writeFileSync(path.join(__dirname, '..', 'src', 'content', 'dictionary.ts'), out);
console.log(`Wrote ${list.length} words, ${(out.length / 1024).toFixed(0)} KB`);
